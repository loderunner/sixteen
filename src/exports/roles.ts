import {
  type Palette,
  type PaletteNames,
  type PalettePair,
  SIGNAL_ROLES,
  type SwatchNames,
  type Variant,
} from '@/palette';

/**
 * The role name of each of a palette's 16 swatches, in palette order. The
 * page's CSS custom properties and Tailwind tokens and the exported CSS and
 * Tailwind files all use these names.
 */
export const ROLE_NAMES = [
  'surface-0',
  'surface-1',
  'surface-2',
  'surface-3',
  'ink-0',
  'ink-1',
  'ink-2',
  'hue-0',
  'hue-1',
  'hue-2',
  'hue-3',
  ...SIGNAL_ROLES.map((role) => `signal-${role}` as const),
] as const;

/** Everything an exporter needs. */
export type ExportInput = {
  /** The palette pair. */
  pair: PalettePair;
  /** Names of the palette and its groups. */
  names: PaletteNames;
  /** Each swatch's name, when loaded. */
  swatchNames?: SwatchNames;
  /** Where the palette lives, to credit in the file. */
  url?: string;
};

/** A file to download or copy. */
export type ExportFile = {
  /** File name, with extension. */
  filename: string;
  /** Media type. */
  mime: string;
  /** The file's text. */
  content: string;
};

/**
 * A palette name as a lowercase, dash-separated identifier.
 *
 * @param name - e.g. `Red Planet`.
 *
 * @example
 * slugOf('Red Planet'); // 'red-planet'
 */
export function slugOf(name: string): string {
  return name
    .normalize('NFKD')
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .toLowerCase();
}

/** One of the 16 role names. */
export type RoleName = (typeof ROLE_NAMES)[number];

/**
 * The hex of each role of a palette.
 *
 * @param palette - One variant of a pair.
 */
export function hexByRole({
  surface,
  ink,
  hue,
  signal,
}: Palette): Record<RoleName, string> {
  return {
    'surface-0': surface[0].hex,
    'surface-1': surface[1].hex,
    'surface-2': surface[2].hex,
    'surface-3': surface[3].hex,
    'ink-0': ink[0].hex,
    'ink-1': ink[1].hex,
    'ink-2': ink[2].hex,
    'hue-0': hue[0].hex,
    'hue-1': hue[1].hex,
    'hue-2': hue[2].hex,
    'hue-3': hue[3].hex,
    'signal-red': signal[0].hex,
    'signal-orange': signal[1].hex,
    'signal-yellow': signal[2].hex,
    'signal-green': signal[3].hex,
    'signal-rare': signal[4].hex,
  };
}

/** Both variants, dark first. */
export const VARIANTS: readonly Variant[] = ['dark', 'light'];

/**
 * The first line of every exported file.
 *
 * @param input - The export input.
 */
export function creditOf({ pair, names, url }: ExportInput): string {
  const source = url === undefined ? '' : ` (${url})`;
  return `${names.palette}, generated by Nord-like from ${pair.seed}${source}.`;
}
